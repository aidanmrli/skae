@dataclass(frozen=True)
class TransitionRichBasinPartitionSystem:
    """Definition of one system in the fixed transition-rich shortlist."""

    system_key: str
    env_name: str
    system_group: str
    basin_count: int
    paper_role: str

    @property
    def system_slug(self) -> str:
        return self.system_key.replace(":", "_")


